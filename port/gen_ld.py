#!/usr/bin/env python3
"""Generates the 3DS port's linker script and overlay table from pokeheartgold's main.lsf.

On the DS, overlays share memory and are loaded from the card as needed. In the port they are all
resident; "loading" overlay N restores its initialised data, clears its BSS and runs its static
initialisers (.sinit), as a fresh load from the card would. For that, each overlay's .data, .bss
and .sinit go in sections of their own, and SDK_OVERLAY_<name>_ID gets the overlay's number
(its place in main.lsf, the same as in the ROM's overlay table).

    python3 port/gen_ld.py pokeheartgold/main.lsf <3dsx.ld> build-3ds/port.ld build-3ds/gen/overlays.c
"""
import re
import sys


def parse_lsf(path):
    blocks = []  # (kind, name, [objects])
    cur = None
    for raw in open(path):
        line = raw.split("#")[0].strip()
        m = re.match(r"(Static|Autoload|Overlay)\s+(\S+)", line)
        if m:
            cur = (m.group(1), m.group(2), [])
            blocks.append(cur)
            continue
        m = re.match(r"Object\s+(\S+)", line)
        if m and cur:
            cur[2].append(m.group(1).split("/")[-1])
    return blocks


def main():
    lsf, base_ld, out_ld, out_c = sys.argv[1:5]
    blocks = parse_lsf(lsf)
    overlays = [b for b in blocks if b[0] == "Overlay"]

    data_secs, bss_secs, syms = [], [], []
    for i, (_, name, objs) in enumerate(overlays):
        syms.append(f"SDK_OVERLAY_{name}_ID = {i};")
        objs = objs or ["__none__"]
        each = lambda what, keep=False: "\n\t\t".join(
            (f"KEEP( */{o}({what}) )" if keep else f"*/{o}({what})") for o in objs)
        data_secs.append(f"""	.ovl{i}_data ALIGN(4) :
	{{
		__ovl{i}_sinit_start = .;
		{each(".sinit", True)}
		__ovl{i}_sinit_end = .;
		__ovl{i}_data_start = .;
		{each(".data .data.*")}
		. = ALIGN(4);
		__ovl{i}_data_end = .;
	}} : data
""")
        bss_secs.append(f"""	.ovl{i}_bss ALIGN(4) (NOLOAD) :
	{{
		__ovl{i}_bss_start = .;
		{each(".bss .bss.* COMMON")}
		. = ALIGN(4);
		__ovl{i}_bss_end = .;
	}} : data
""")

    ld = open(base_ld).read()
    # The DS's ITCM/DTCM sections are ordinary code and data here.
    ld = ld.replace("\t\t*(.text)\n", "\t\t*(.text)\n\t\t*(.itcm .itcm.*)\n", 1)
    main_sinit = """	.sinit_main ALIGN(4) :
	{
		__sinit_main_start = .;
		KEEP( *(.sinit) )
		__sinit_main_end = .;
	} : data

"""
    ld = ld.replace("\t.data :\n", "".join(data_secs) + main_sinit + "\t.data :\n", 1)
    ld = ld.replace("\t\t*(.data.*)\n", "\t\t*(.data.*)\n\t\t*(.dtcm .dtcm.*)\n", 1)
    ld = ld.replace("\t__bss_start__ = .;\n", "".join(bss_secs) + "\t__bss_start__ = .;\n", 1)
    ld = ld.replace("/DISCARD/ : { *(.group .comment .note) }",
                    "/DISCARD/ : { *(.group .comment .note .exceptix .exception .version) }")
    ld += "\n/* Overlay numbers, and the values NitroSDK's crt0 and OS_InitArena expect from the linker */\n"
    ld += "\n".join(syms) + "\n"
    ld += """
SDK_AUTOLOAD_DTCM_START = 0x027E0000 + 0x08000000;
SDK_MAIN_ARENA_LO = 0x02000000 + 0x08000000;
SDK_SECTION_ARENA_EX_START = 0x02400000 + 0x08000000;
SDK_SECTION_ARENA_ITCM_START = 0x01FF8000 + 0x08000000;
SDK_SECTION_ARENA_DTCM_START = 0x027E0000 + 0x08000000;
SDK_SYS_STACKSIZE = 0;
SDK_IRQ_STACKSIZE = 2048;
"""
    with open(out_ld, "w") as f:
        f.write(ld)

    n = len(overlays)
    c = ['// Generated by port/gen_ld.py from main.lsf: the overlays, all resident.',
         '#include <stdint.h>', '#include <stdlib.h>', '#include <string.h>', '#include "port.h"', '']
    for i in range(n):
        c.append(f"extern char __ovl{i}_sinit_start[], __ovl{i}_sinit_end[], __ovl{i}_data_start[], "
                 f"__ovl{i}_data_end[], __ovl{i}_bss_start[], __ovl{i}_bss_end[];")
    c.append("extern char __sinit_main_start[], __sinit_main_end[];")
    c.append("""
typedef struct {
    const char *name;
    char *sinit_start, *sinit_end, *data_start, *data_end, *bss_start, *bss_end;
    char *pristine;  // the data as linked, restored on each load
} PortOverlay;
""")
    c.append(f"static PortOverlay sOverlays[{n}] = {{")
    for i, (_, name, _) in enumerate(overlays):
        c.append(f'    {{ "{name}", __ovl{i}_sinit_start, __ovl{i}_sinit_end, __ovl{i}_data_start, '
                 f'__ovl{i}_data_end, __ovl{i}_bss_start, __ovl{i}_bss_end, NULL }},')
    c.append("};")
    c.append(f"""
uint32_t port_overlay_count(void) {{ return {n}; }}

void port_overlays_init(void) {{
    size_t total = 0;
    for (uint32_t i = 0; i < {n}; i++) {{
        PortOverlay *o = &sOverlays[i];
        size_t len = (size_t)(o->data_end - o->data_start);
        if (len) {{
            o->pristine = malloc(len);
            memcpy(o->pristine, o->data_start, len);
            total += len;
        }}
    }}
    port_log("overlays: %d, %u bytes of initial data kept\\n", {n}, (unsigned)total);
}}

static void run_sinit(char *start, char *end) {{
    for (void (**f)(void) = (void (**)(void))start; f < (void (**)(void))end; f++) {{
        if (*f) (*f)();
    }}
}}

void port_overlay_load(uint32_t id) {{
    if (id >= {n}) port_fatal("overlay %lu does not exist", id);
    PortOverlay *o = &sOverlays[id];
    if (o->pristine) memcpy(o->data_start, o->pristine, (size_t)(o->data_end - o->data_start));
    memset(o->bss_start, 0, (size_t)(o->bss_end - o->bss_start));
}}

void port_overlay_start(uint32_t id) {{
    if (id >= {n}) port_fatal("overlay %lu does not exist", id);
    port_log("overlay %lu (%s)\\n", id, sOverlays[id].name);
    run_sinit(sOverlays[id].sinit_start, sOverlays[id].sinit_end);
}}

void port_run_main_sinit(void) {{
    run_sinit(__sinit_main_start, __sinit_main_end);
}}
""")
    with open(out_c, "w") as f:
        f.write("\n".join(c))
    print(f"{len(overlays)} overlays")


if __name__ == "__main__":
    main()
