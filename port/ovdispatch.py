"""Calls into memory that several overlays share, dispatched to the overlay loaded there.

On the DS, overlays that never run together load at the same address (7, 8 and 10 all at
0x0221BE20) and a call is a jump to an address: it runs whichever overlay is loaded. The decomp
names each such target after one of them (ov10_0221BE20), so the port, linking by name, could call
the wrong one (the battle's party screen called the trainer AI: a crash). For every DS address
where two or more overlays define a function (named ovNN_XXXXXXXX), each symbol referenced from
another object gets a trampoline (ld --wrap) that asks port_overlay_dispatch (runtime/overlay.c)
for the function of the overlay loaded there now; when it is the one linked, nothing changes.

    python3 port/ovdispatch.py <obj dir> <out .c>     (prints the symbols to --wrap)
"""
import collections
import glob
import re
import subprocess
import sys

NM = "/opt/devkitpro/devkitARM/bin/arm-none-eabi-nm"
NAME = re.compile(r"^ov(\d+)_([0-9A-F]{8})$")


def nm(args, files):
    out = []
    for i in range(0, len(files), 200):
        out += subprocess.run([NM, "-A"] + args + files[i:i + 200], capture_output=True, text=True).stdout.splitlines()
    return out


def generate(objdir, out):
    files = sorted(glob.glob(f"{objdir}/*.o"))
    defined = {}                                  # symbol -> defining object
    at = collections.defaultdict(set)             # DS address -> {(overlay, symbol)}
    for line in nm(["--defined-only"], files):
        p = line.split()
        if len(p) != 3 or p[1] != "T":  # (global functions only: a local one can't be linked to by name)
            continue
        obj, sym = p[0].rsplit(":", 1)[0], p[2]
        m = NAME.match(sym)
        if m:
            defined[sym] = obj
            at[int(m.group(2), 16)].add((int(m.group(1)), sym))
    shared = {a: s for a, s in at.items() if len({ov for ov, _ in s}) > 1}
    referenced = collections.defaultdict(set)     # symbol -> objects referring to it
    for line in nm(["-u"], files):
        p = line.split()
        if len(p) >= 2:
            referenced[p[-1]].add(p[0].rsplit(":", 1)[0])
    wrap = sorted(sym for s in shared.values() for _, sym in s
                  if any(o != defined[sym] for o in referenced.get(sym, ())))
    wrapset = set(wrap)
    ref = lambda sym: f"__real_{sym}" if sym in wrapset else sym

    c = ['/* Generated by port/ovdispatch.py: calls into memory several overlays share. */',
         'typedef struct { unsigned char ov; void *fn; } OvCand;',
         'typedef struct { unsigned long ds; void *dflt; const char *name; unsigned char n; const OvCand *c; } OvDispatch;']
    names = sorted({ref(sym) for s in shared.values() for _, sym in s})
    c += [f"extern char {n}[];" for n in names]
    tables, entries = [], []
    for i, sym in enumerate(wrap):
        a = int(NAME.match(sym).group(2), 16)
        cands = sorted(shared[a])
        tables.append(f"static const OvCand c{i}[] = {{ " + ", ".join(f"{{ {ov}, {ref(s)} }}" for ov, s in cands) + " };")
        entries.append(f"    {{ 0x{a:08X}, __real_{sym}, \"{sym}\", {len(cands)}, c{i} }},")
        c.append(f'__asm__(".arm\\n.balign 4\\n.global __wrap_{sym}\\n.type __wrap_{sym}, %function\\n__wrap_{sym}:\\n'
                 f'\\tpush {{r0-r3, r4, lr}}\\n\\tldr r0, ={i}\\n\\tbl port_overlay_dispatch\\n\\tmov r12, r0\\n'
                 f'\\tpop {{r0-r3, r4, lr}}\\n\\tbx r12\\n\\t.ltorg\\n");')
    c += tables
    c.append("const OvDispatch port_ovdispatch[] = {")
    c += entries
    c.append("};")
    c.append(f"const unsigned port_ovdispatch_count = {len(wrap)};")
    open(out, "w").write("\n".join(c) + "\n")
    return wrap


if __name__ == "__main__":
    print("\n".join(generate(sys.argv[1], sys.argv[2])))
